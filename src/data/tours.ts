export function getTourBySlug(slug: string): Tour | undefined {
  return tours.find((t) => t.slug === slug);
}

export function getTourById(id: string): Tour | undefined {
  return tours.find((t) => t.id === id);
}

export function getFeaturedTours(): Tour[] {
  return tours.filter((t) => t.isFeatured);
}

export function getPopularTours(): Tour[] {
  return tours.filter((t) => t.isPopular);
}

export function getToursByDestination(destinationId: string): Tour[] {
  return tours.filter((t) => t.destinationId === destinationId);
}

export function getToursByCategory(category: string): Tour[] {
  return tours.filter((t) => t.category === category);
}

export function getCategories(): string[] {
  return [...new Set(tours.map((t) => t.category))];
}
